from pydantic import BaseModel, Field
from datetime import datetime
from typing import Optional


class SensorReading(BaseModel):
    sensor_id: str
    temperature: float = Field(..., description="Temperature in Celsius")
    humidity: float = Field(..., description="Relative humidity percentage")
    co2_ppm: Optional[float] = Field(None, description="CO2 concentration in ppm")
    # CS5055: None si el nodo no envía lectura MQ-7 (antes 0.0 → "0 ppm" ficticio).
    # Compatible: los clientes que sí envían co_ppm no cambian.
    co_ppm: Optional[float] = Field(None, description="Carbon monoxide concentration in ppm (MQ7 sensor); None = sin lectura")
    camera_occupancy: Optional[int] = Field(
        None,
        description=(
            "Current headcount measured by the sensor node's camera (MediaPipe "
            "line-crossing count). Persisted alongside the CO2-derived "
            "actual_occupancy to validate/calibrate the mass-balance proxy. "
            "Not a model feature; None when the node has no camera."
        ),
    )
    is_simulated: bool = Field(False, description="True when generated by the dev tool, not real hardware")
    timestamp: datetime = Field(default_factory=datetime.utcnow)

    # ── CS5055 — telemetría del nodo ESP32 (ccs/<room>/telemetry). Todos
    # opcionales: un nodo/simulador viejo que no los envíe sigue siendo válido.
    power_w: Optional[float] = Field(None, ge=0, description="Potencia medida por INA219 (W)")
    current_ma: Optional[float] = Field(None, ge=0, description="Corriente medida por INA219 (mA)")
    bus_voltage_v: Optional[float] = Field(None, ge=0, description="Tensión de bus medida por INA219 (V)")
    fan_pwm: Optional[float] = Field(None, ge=0, le=100, description="Ciclo PWM aplicado al ventilador (0-100 %)")
    heater_on: Optional[bool] = Field(None, description="Calefactor PTC encendido")
    alarm_active: Optional[bool] = Field(None, description="Alarma local CO activa (buzzer + LED, ventilador forzado 100 %)")
    node_online: Optional[bool] = Field(None, description="Estado LWT del nodo (ccs/<room>/status)")
    rssi_dbm: Optional[float] = Field(None, description="Intensidad de señal WiFi (dBm)")
    latency_ms: Optional[float] = Field(None, ge=0, description="Latencia sensado→actuación del ciclo previo (ms)")
    uptime_s: Optional[float] = Field(None, ge=0, description="Segundos desde el último arranque del nodo")
    data_origin: Optional[str] = Field(
        None,
        description="Procedencia: 'node' (hardware), 'simulator' (herramienta dev) o 'seed' (dataset sintético)",
    )
